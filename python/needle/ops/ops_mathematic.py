class Conv(TensorOp):
    def __init__(self, stride: Optional[int] = 1, padding: Optional[int] = 0):
        self.stride = stride
        self.padding = padding

    def compute(self, A, B):
        ### BEGIN YOUR SOLUTION
        A = A.pad(((0, 0), (self.padding, self.padding), (self.padding, self.padding), (0, 0)))
        N, H, W, C_in = A.shape
        K, _, _, C_out = B.shape
        Ns, Hs, Ws, Cs = A.strides
        H_out = (H - K) // self.stride + 1
        W_out = (W - K) // self.stride + 1
        inner_dim = K * K * C_in
        A = A.as_strided((N, H_out, W_out, K, K, C_in),
                         (Ns, Hs * self.stride, Ws * self.stride, Hs, Ws, Cs)).compact()
        out = A.reshape((N * H_out * W_out, inner_dim)) @ B.compact().reshape((inner_dim, C_out))
        return out.reshape((N, H_out, W_out, C_out))
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        A, B = node.inputs
        K = B.shape[0]
        if self.stride > 1:
            out_grad = dilate(out_grad, (1, 2), self.stride - 1)
        B_t = flip(B, (0, 1)).transpose((2, 3))
        A_grad = conv(out_grad, B_t, padding=K - 1 - self.padding)
        A_t = A.transpose((0, 3))
        out_grad_t = out_grad.transpose((0, 1)).transpose((1, 2))
        B_grad = conv(A_t, out_grad_t, padding=self.padding)
        B_grad = B_grad.transpose((0, 1)).transpose((1, 2))
        return A_grad, B_grad
        ### END YOUR SOLUTION


def conv(a, b, stride=1, padding=1):
    return Conv(stride, padding)(a, b)


